/**
 * 品牌色卡生成物的窄接口（**类型与数据分开放**）。
 *
 * 为什么要把这个类型单独一个文件、而不是放进 `palettes-beads.ts`：
 * 那个文件是 `tool/bead-palettes.mjs` **整个覆盖生成**的，任何手写内容都会在下次
 * 重跑抓取时被抹掉。类型是手写的、需要长期演进（加字段、改注释），
 * 数据是生成的、随时可重新产出——两者生命周期不同，混在一起必然出事故。
 *
 * 这也解释了为什么这里**没有 `source` 字段**：这个接口只描述上游数据能给的东西
 * （颜色 + 号色 + 名字）。"来源是不是官方"这类业务声明由 `palettes.ts` 在组装
 * `PRESETS` 时统一加——生成物不该知道业务语义，否则改一次语义就得重跑抓取脚本。
 */
export interface BeadBrandPalette {
  /** 预置卡 id（`--palette <id>` 与页内 API 用它引用） */
  id: string
  /** 面向用户的名称（会进 UI 下拉与取色器分组名，保持简短） */
  name: string
  /** 一句话说明 */
  desc: string
  /** `#rrggbb` 小写数组 */
  colors: string[]
  /** 号色，与 `colors` **按下标一一对应**（等长由生成脚本自校验保证） */
  codes: string[]
}
