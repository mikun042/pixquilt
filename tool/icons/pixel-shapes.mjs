/** 高级：齿轮（6 齿 + 中心孔） */
const gear = () => {
  const g = new Grid()
  g.disc(15.5, 15.5, 10)
  for (let k = 0; k < 6; k++) {
    const a = (k / 6) * Math.PI * 2 - Math.PI / 2
    const cx = 15.5 + Math.cos(a) * 12.5
    const cy = 15.5 + Math.sin(a) * 12.5
    g.disc(cx, cy, 4)
  }
  // 中心孔（用 0 挖空；evenodd 会把它变透明）
  for (let y = 0; y < 32; y++)
    for (let x = 0; x < 32; x++) if (Math.hypot(x - 15.5, y - 15.5) <= 4.5) g.set(x, y, 0)
  return g
}

