/** 右栏开关：左栏开关的水平镜像 */
const panelRight = () => panelLeft().mirrorX()

/** 画布最大化：四角向外的 L 形折角（四角等宽、完全对称） */
const maximize = () => {
  const g = new Grid()
  const L = (x, y, sx, sy) => {
    for (let k = 0; k < 12; k++)
      for (let t = 0; t < 3; t++) {
        g.set(x + sx * k, y + sy * t, 1)
        g.set(x + sx * t, y + sy * k, 1)
      }
  }
  L(2, 2, 1, 1)
  L(29, 2, -1, 1)
  L(2, 29, 1, -1)
  L(29, 29, -1, -1)
  return g
}

