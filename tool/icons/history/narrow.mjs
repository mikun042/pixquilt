import { readFileSync, writeFileSync } from 'node:fs'
const p = new URL('./icons.mjs', import.meta.url)
let s = readFileSync(p, 'utf8')
const CRLF = String.fromCharCode(13,10), LF = String.fromCharCode(10)
const had = s.includes(CRLF); if (had) s = s.split(CRLF).join(LF)
const A = (lines) => 'A([\n' + lines.map(l => `    '${l.padEnd(32,'.')}',`).join('\n') + '\n  ])'
const start = s.indexOf('const pencil = ')
const end = s.indexOf('\n\n', start)
// 笔头收窄：最宽从 21 格降到 15 格，避免像"刀"
const next = `const pencil = () =>
  ${A([
    '................................',
    '................................',
    '................................',
    '..........................####..',
    '.........................####...',
    '........................####....',
    '.......................####.....',
    '......................####......',
    '.....................####.......',
    '....................####........',
    '...................####.........',
    '..................####..........',
    '.................####...........',
    '................####............',
    '.............########...........',
    '............#########...........',
    '...........##########...........',
    '..........###########...........',
    '.........############...........',
    '........#############...........',
    '.......##############...........',
    '......###############...........',
    '.....################...........',
    '....#################...........',
    '...##################...........',
    '..###################...........',
    '..##################............',
    '..#################.............',
    '..################..............',
    '..###############...............',
    '..##############................',
    '..#############.................',
  ])}`
s = s.slice(0, start) + next + s.slice(end)
writeFileSync(p, had ? s.split(LF).join(CRLF) : s)
console.log('画笔笔头已收窄')
