// 结构全部参照上一轮从 SVG 栅格化结果里提取的掩码（那是 SVG 帮我们找对的形状）。
import { readFileSync, writeFileSync } from 'node:fs'

const p = new URL('./icons.mjs', import.meta.url)
let s = readFileSync(p, 'utf8')
const CRLF = String.fromCharCode(13, 10)
const LF = String.fromCharCode(10)
const had = s.includes(CRLF)
if (had) s = s.split(CRLF).join(LF)

const A = (lines) => 'A([\n' + lines.map((l) => `    '${l.padEnd(32, '.')}',`).join('\n') + '\n  ])'

function replaceFn(name, body) {
  const start = s.indexOf(`const ${name} = `)
  if (start < 0) throw new Error(`找不到 ${name}`)
  const end = s.indexOf('\n\n', start)
  if (end < 0) throw new Error(`找不到 ${name} 的结尾`)
  s = s.slice(0, start) + body + s.slice(end)
}

