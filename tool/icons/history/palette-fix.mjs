// 调色盘：重画。上一版我改坏了（误删右半边，成了"C"形）——这次逐行核对左右边界。
//
// 结构：**完整圆盘** + 三个**相互隔开**的颜料孔（上/左/下）+ 右下**拇指孔**（开口）。
// 关键两条：
//   · 三个孔必须相互隔开（更早一版孔太大、连成一片，看着只剩两个圆点）
//   · 圆盘左右边界要闭合（上一版误删右边，成了 C 形）
import { readFileSync, writeFileSync } from 'node:fs'

const p = new URL('./icons.mjs', import.meta.url)
let s = readFileSync(p, 'utf8')
const CRLF = String.fromCharCode(13, 10)
const LF = String.fromCharCode(10)
const had = s.includes(CRLF)
if (had) s = s.split(CRLF).join(LF)

const A = (lines) => 'A([\n' + lines.map((l) => `    '${l.padEnd(32, '.')}',`).join('\n') + '\n  ])'

const start = s.indexOf('const palette = ')
const end = s.indexOf('\n\n', start)
if (start < 0 || end < 0) throw new Error('定位失败')

const next = `const palette = () =>
  ${A([
    '................................',
    '................................',
    '..........############..........',
    '........################........',
    '.......##################.......',
    '......####################......',
    '.....######..######..######.....',
    '....######...######...######....',
    '....#####....######....#####....',
    '...######...............######..',
    '...#####.................#####..',
    '..######.................######.',
    '..#####...................#####.',
    '..#####...................#####.',
    '..#####...................#####.',
    '..#####...................#####.',
    '..#####...................#####.',
    '..#####...................#####.',
    '..######.................######.',
    '...#####.................#####..',
    '...######...............######..',
    '....#####.....####......#####...',
    '.....#####....####.....#####....',
    '......#####...####....#####.....',
    '.......#####.........#####......',
    '........######.......#####......',
    '..........#############.........',
    '...........##########...........',
    '................................',
    '................................',
    '................................',
    '................................',
  ])}`
s = s.slice(0, start) + next + s.slice(end)
writeFileSync(p, had ? s.split(LF).join(CRLF) : s)
console.log('调色盘已重画（左右闭合 + 三孔隔开）')
