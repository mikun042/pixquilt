// 手绘重画 8 个待像素化图标（第一组：画笔 / 填充桶）。
//
// 做法（上一轮定的）：**用 SVG 帮我们确定形状结构，然后照着结构在网格上逐格画**。
// 为什么不再调 SVG：SVG 栅格化的边缘是"抗锯齿后二值化"的参差感，与手绘的干净阶梯不同源，
// 试了 6 轮（加粗 stroke、调阈值、提分辨率、改实心）都只能改善一点，无法同等质量。
// 手绘这条路已经成功做出 12 个（矩形/椭圆/选区/齿轮/转换…），质量稳定。
import { readFileSync, writeFileSync } from 'node:fs'

const p = new URL('./icons.mjs', import.meta.url)
let s = readFileSync(p, 'utf8')
const CRLF = String.fromCharCode(13, 10)
const LF = String.fromCharCode(10)
const had = s.includes(CRLF)
if (had) s = s.split(CRLF).join(LF)

const A = (lines) => 'A([\n' + lines.map((l) => `    '${l.padEnd(32, '.')}',`).join('\n') + '\n  ])'

function replaceFn(name, body) {
  const start = s.indexOf(`const ${name} = `)
  if (start < 0) throw new Error(`找不到 ${name}`)
  const end = s.indexOf('\n\n', start)
  if (end < 0) throw new Error(`找不到 ${name} 的结尾`)
  s = s.slice(0, start) + body + s.slice(end)
}

/* 画笔：三段分明——**细笔杆**（右上）→ **宽箍**（中间，明显凸出）→ **实心笔头**（左下楔形）。
   结构参照来自 SVG 版（它把"杆细、头宽"的关系表达对了），这里逐格落实。
   关键：笔杆 4 格、箍 8 格、笔头最宽 11 格，宽度阶梯明显才读得出是"笔"。 */
replaceFn(
  'pencil',
  `const pencil = () =>
  ${A([
    '................................',
    '................................',
    '................................',
    '..........................####..',
    '.........................####...',
    '........................####....',
    '.......................####.....',
    '......................####......',
    '.....................####.......',
    '....................####........',
    '...................####.........',
    '..................####..........',
    '.................####...........',
    '................####............',
    '.............########...........',
    '............##########..........',
    '...........###########..........',
    '..........############..........',
    '.........#############..........',
    '........##############..........',
    '.......###############..........',
    '......################..........',
    '.....#################..........',
    '....##################..........',
    '...###################..........',
    '..####################..........',
    '..###################...........',
    '..##################............',
    '..#################.............',
    '..################..............',
    '..###############...............',
    '..##############................',
  ])}`,
)

/* 填充桶：**提梁**（拱，两端落到桶口）→ **桶口**（横向一片）→ **实心桶身**（上宽下窄）
   → **右下分离的一滴**。
   结构参照来自 SVG 版（它把"提梁与桶身留空档"这点修对了），这里逐格落实。
   关键：提梁与桶口之间留 2 格空档，否则会糊成一个"灯笼"（上一轮踩过）。 */
replaceFn(
  'bucket',
  `const bucket = () =>
  ${A([
    '................................',
    '................................',
    '..........##########............',
    '........##############..........',
    '.......####........####.........',
    '......####..........####........',
    '......###............###........',
    '......####..........####........',
    '.......####........####.........',
    '................................',
    '................................',
    '....########################....',
    '....########################....',
    '....########################....',
    '....########################....',
    '.....######################.....',
    '.....######################.....',
    '......####################......',
    '......####################......',
    '.......##################.......',
    '.......##################.......',
    '........################........',
    '........################........',
    '.........##############.........',
    '.........##############.........',
    '..........############..........',
    '..........############..........',
    '...........##########..####.....',
    '...........##########.######....',
    '............########..######....',
    '......................######....',
    '.......................####.....',
  ])}`,
)

writeFileSync(p, had ? s.split(LF).join(CRLF) : s)
console.log('画笔 / 填充桶 已手绘重画')
